import { z } from 'zod';
import { CommitSchema, DigestSchema } from './schema';
import { hashArtifact, hashBytes } from './identity';

const DecimalId = z
  .union([z.number().int().positive(), z.string().regex(/^[1-9]\d*$/u)])
  .transform(String);
const DeploymentSchema = z.object({
  id: DecimalId,
  sha: CommitSchema,
  ref: z.literal('main'),
  environment: z.literal('github-pages'),
});
const StatusSchema = z.object({
  state: z.literal('success'),
  environment_url: z.url(),
  log_url: z.url(),
});
/** Consume actual API state, not a candidate, course flag or lagging release record. */
export function parseActualDeployment(
  deploymentInput: unknown,
  statusInput: unknown,
  repository: string,
  siteUrl: string,
) {
  const deployment = DeploymentSchema.parse(deploymentInput),
    status = StatusSchema.parse(statusInput);
  if (new URL(status.environment_url).href !== new URL(siteUrl).href)
    throw new Error('Deployment site URL differs');
  const log = new URL(status.log_url),
    prefix = '/' + repository + '/actions/runs/';
  if (log.origin !== 'https://github.com' || !log.pathname.startsWith(prefix))
    throw new Error('Deployment has no trusted run');
  const run = /^([1-9]\d*)\/job\/([1-9]\d*)$/u.exec(log.pathname.slice(prefix.length));
  if (!run) throw new Error('Deployment run URL is invalid');
  return {
    deploymentId: deployment.id,
    workflowHeadCommit: deployment.sha,
    runId: run[1]!,
    siteUrl: new URL(siteUrl).href,
  };
}

const LEGACY_KEYS = new Set([
  'course_id',
  'revision',
  'draft_source',
  'draft_dist',
  'learning_input',
  'source',
  'head',
  'dist',
  'course',
  'provenance',
  'quality_id',
  'quality_digest',
  'report_id',
  'report_digest',
  'workflow',
  'page_url',
]);
/** Annotated-tag migration boundary only. Product Source and workflow Source remain distinct. */
export function parseLegacyBinding(
  message: string,
  targetCommit: string,
  deploymentHead: string,
  runId: string,
) {
  const fields = new Map<string, string>();
  for (const token of message.trim().split(/\s+/u)) {
    const separator = token.indexOf('=');
    const key = token.slice(0, separator),
      value = token.slice(separator + 1);
    if (separator <= 0 || !value || !LEGACY_KEYS.has(key) || fields.has(key))
      throw new Error('Invalid or duplicate historical binding');
    fields.set(key, value);
  }
  const sourceCommit = CommitSchema.parse(fields.get('source'));
  const workflowHeadCommit = CommitSchema.parse(fields.get('head'));
  const artifactDigest = DigestSchema.parse(fields.get('dist'));
  const workflow = /^([1-9]\d*)-([1-9]\d*)$/u.exec(fields.get('workflow') ?? '');
  const pageUrl = z.url().parse(fields.get('page_url'));
  if (
    sourceCommit !== targetCommit ||
    workflowHeadCommit !== deploymentHead ||
    workflow?.[1] !== runId
  )
    throw new Error('Historical tag does not belong to the current deployment');
  return {
    sourceCommit,
    workflowHeadCommit,
    runId,
    artifactDigest,
    pageUrl,
    projection: 'authoring' as const,
    artifactDigestFormat: 'legacy-canonical-dist' as const,
    inventoryDigest: undefined,
    publicContentDigest: undefined,
  };
}

/** Compare every expected generated byte, including referenced assets. No approval is created. */
export async function matchPublicTree(
  directory: string,
  fetchFile: (relative: string) => Promise<Uint8Array>,
) {
  const expected = await hashArtifact(directory);
  let index = 0;
  const completion = await Promise.allSettled(
    Array.from({ length: Math.min(4, expected.files.length) }, async () => {
      while (index < expected.files.length) {
        const file = expected.files[index++]!;
        let actual: Uint8Array;
        try {
          actual = await fetchFile(file.path);
        } catch (error: unknown) {
          // Only the public path and bounded HTTP status may reach the CLI message.
          const detail =
            error instanceof Error &&
            /^Public baseline request failed: [1-5]\d{2}$/u.test(error.message)
              ? error.message
              : error instanceof Error && error.name === 'TimeoutError'
                ? 'request timeout'
                : 'request failed';
          throw new Error(file.path + ' (' + detail + ')', { cause: error });
        }
        if (actual.length !== file.bytes || hashBytes(actual) !== file.sha256)
          throw new Error('Public content differs from recorded source: ' + file.path);
      }
    }),
  );
  const failure = completion.find((result) => result.status === 'rejected');
  if (failure?.status === 'rejected')
    throw new Error(
      'Public content could not be verified: ' +
        (failure.reason instanceof Error ? failure.reason.message : 'unknown failure'),
      { cause: failure.reason },
    );
  return { digest: expected.digest, files: expected.files.length };
}
