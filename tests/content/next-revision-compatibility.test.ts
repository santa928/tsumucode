import { beforeAll, expect, it } from 'vitest';
import { compileCourse } from '../../scripts/content/compileCourse';
import type { CourseManifest } from '../../src/core/content/types';
import type {
  ExerciseDraft,
  ProgressRepository,
  RepositorySnapshot,
} from '../../src/core/persistence/contracts';
import { ContentProgressMigrationService } from '../../src/core/persistence/contentProgressMigration';
import { migrateRepositorySnapshot } from '../../src/adapters/persistence/indexeddb/migrateProgress';
import previewFixture from '../fixtures/progress/release-flow-preview28.json';
// This fixture was generated by synthetic real UI actions, never from a learner's saved data.
const baseline = '2026-10-27.1',
  preview = '2026-10-28.1',
  now = '2026-10-29T07:00:00Z';
let course: CourseManifest;
beforeAll(async () => {
  course = (await compileCourse('content/next')).runtime;
});
function sample(revision: string): RepositorySnapshot {
  const snapshot = migrateRepositorySnapshot(structuredClone(previewFixture), now);
  const progress = snapshot.courses['next']!;
  const lesson = course.phases
    .flatMap((row) => row.chapters.flatMap((chapter) => chapter.lessons))
    .find((row) => row.id === progress.currentLessonId)!;
  const exercise = lesson.exercises[0]!;
  const files = Object.fromEntries(exercise.files.map((file) => [file.path, file.content]));
  const selected = exercise.files.find((file) => file.editable) ?? exercise.files[0]!;
  files[selected.path] = selected.content + '\n// synthetic preview draft retained\n';
  const draft: ExerciseDraft = {
    courseId: course.id,
    lessonId: lesson.id,
    exerciseId: exercise.id,
    workspaceId: exercise.workspaceId,
    contentRevision: revision,
    editRevision: 3,
    files,
    selectedFile: selected.path,
    cursors: { [selected.path]: { anchor: 2, head: 4 } },
    validationHistory: [],
    revealedHintIds: [],
    lastPassingSnapshots: {},
    updatedAt: now,
  };
  return {
    ...snapshot,
    courses: { ...snapshot.courses, next: { ...progress, contentRevision: revision } },
    drafts: { ...snapshot.drafts, ['next:' + exercise.workspaceId]: draft },
  };
}
function service() {
  const noIo = new Proxy(
    {},
    {
      get() {
        throw Error('Pure migration must not read or mutate repository');
      },
    },
  ) as ProgressRepository;
  const value = new ContentProgressMigrationService(noIo, {
    now: () => now,
    id: () => 'synthetic-migration',
  });
  value.registerCourse(course);
  return value;
}
it('keeps the published lesson revision independent from the UI-only preview bump', () => {
  expect(course.progressMigrations).toContainEqual({
    fromRevision: preview,
    toRevision: baseline,
    steps: [],
  });
  expect(
    course.progressMigrations.some(
      (row) => row.fromRevision === baseline && row.toRevision === preview,
    ),
  ).toBe(false);
});
it.each(['2026-10-24.1', baseline, preview])(
  'preserves courses, editable source, cursor and passing history from %s',
  async (revision) => {
    const input = sample(revision),
      before = structuredClone(input),
      migration = service();
    const result = await migration.migrateSnapshotWithNotices(input);
    const nextDraft = Object.keys(input.drafts).find((key) => key.startsWith('next:'))!;
    expect(result.snapshot.courses['next']).toEqual({
      ...input.courses['next'],
      contentRevision: course.revision,
    });
    expect(result.snapshot.drafts[nextDraft]).toEqual({
      ...input.drafts[nextDraft],
      contentRevision: course.revision,
    });
    for (const [id, value] of Object.entries(input.courses))
      if (id !== 'next') expect(result.snapshot.courses[id]).toEqual(value);
    for (const [key, value] of Object.entries(input.drafts))
      if (key !== nextDraft) expect(result.snapshot.drafts[key]).toEqual(value);
    expect(result.snapshot.quarantined).toEqual(input.quarantined);
    expect(result.notices).toEqual([]);
    expect(input).toEqual(before);
  },
);
it('rejects an unknown revision without mutation or a reset', async () => {
  const input = sample('unrecognized-future-revision'),
    before = structuredClone(input);
  await expect(service().migrateSnapshotWithNotices(input)).rejects.toThrow(/未知またはfuture/u);
  expect(input).toEqual(before);
});
it('reapplying the declared preview correction does not change data or add reset notices', async () => {
  const migration = service(),
    first = await migration.migrateSnapshotWithNotices(sample(preview));
  const again = await migration.migrateSnapshotWithNotices(first.snapshot);
  expect(again.snapshot).toEqual(first.snapshot);
  expect(again.notices).toEqual([]);
});
